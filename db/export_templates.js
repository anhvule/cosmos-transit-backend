// Exports the contents of db/cosmos.db (event_templates table) to two
// human-readable formats so the descriptions are reviewable without
// opening SQLite:
//
//   db/cosmos_seed.json  — the full 5,348 events, structured
//   db/cosmos_seed.md    — same data grouped by (lens, kind) for reading

const Database = require('better-sqlite3');
const fs = require('fs');
const path = require('path');

const DB_PATH   = path.join(__dirname, 'cosmos.db');
const JSON_PATH = path.join(__dirname, 'cosmos_seed.json');
const MD_PATH   = path.join(__dirname, 'cosmos_seed.md');

const db = new Database(DB_PATH, { readonly: true });

const rows = db.prepare(`
  SELECT lens, kind, transit_planet, natal_planet, target_house,
         target_angle, special_label, lord_house, phase,
         display_name, description
  FROM event_templates
  ORDER BY lens, kind, transit_planet, natal_planet,
           target_house, target_angle, special_label, lord_house, phase
`).all();

// Strip empty-default columns from each row so the JSON is tighter.
const trimmed = rows.map(r => {
  const out = { lens: r.lens, kind: r.kind };
  if (r.transit_planet) out.transit_planet = r.transit_planet;
  if (r.natal_planet)   out.natal_planet   = r.natal_planet;
  if (r.target_house)   out.target_house   = r.target_house;
  if (r.target_angle)   out.target_angle   = r.target_angle;
  if (r.special_label)  out.special_label  = r.special_label;
  if (r.lord_house)     out.lord_house     = r.lord_house;
  out.phase        = r.phase;
  out.display_name = r.display_name;
  out.description  = r.description;
  return out;
});

fs.writeFileSync(JSON_PATH, JSON.stringify(trimmed, null, 2) + '\n');

// Markdown grouped by (lens, kind) — much easier to skim.
const lines = [];
lines.push(`# cosmos.db event templates (${rows.length} rows)\n`);
lines.push('Generated by `db/export_templates.js`. Do not edit by hand — it is\n' +
           'derived from the DB. To change descriptions, edit `db/seed_templates.js`\n' +
           'and re-run `node db/seed_templates.js`, then re-export.\n');

let curLens = null, curKind = null;
for (const r of rows) {
  if (r.lens !== curLens) {
    lines.push(`\n## ${r.lens}\n`);
    curLens = r.lens;
    curKind = null;
  }
  if (r.kind !== curKind) {
    lines.push(`\n### ${r.kind}\n`);
    curKind = r.kind;
  }
  lines.push(`- **${r.display_name}**  (${r.description.length} chars)`);
  lines.push(`  ${r.description}\n`);
}
fs.writeFileSync(MD_PATH, lines.join('\n'));

console.log(`Exported ${rows.length} rows:`);
console.log(`  ${JSON_PATH}`);
console.log(`  ${MD_PATH}`);
